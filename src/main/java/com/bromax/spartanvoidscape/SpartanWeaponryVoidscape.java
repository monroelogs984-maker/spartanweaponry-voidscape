import net.minecraftforge.registries.RegistryObject;
import tamaized.voidscape.registry.ModTools;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Spartan Weaponry: Voidscape. Voidic Crystal and Corrupt weapons for every Spartan weapon type,
 * using Voidscape's own tool tiers so stats match Voidscape's swords exactly.
 * Recipes mirror Voidscape: netherite Spartan weapon + voidic template + voidic crystal, then
 * voidic weapon + voidic template + tendril (resources/data/.../recipes, generated by tools/gen_assets.py).
 */
@Mod(SpartanWeaponryVoidscape.MODID)
public class SpartanWeaponryVoidscape extends SpartanAddon {
    public static final String MODID = "spartanweaponryvoidscape";
    private static final ResourceLocation VOID_DIMENSION = new ResourceLocation("voidscape", "void");

    public static final WeaponMap WEAPONS = new WeaponMap();
    public static final DeferredRegister<Item> ITEMS = itemRegister(MODID);
    public static final DeferredRegister<WeaponTrait> TRAITS = traitRegister(MODID);
    public static final DeferredRegister<CreativeModeTab> TABS = tabRegister(MODID);

    /** Extra damage while the wielder is inside Voidscape's Void. Magnitude is the multiplier. */
    private static BetterWeaponTrait voidtouched(String name, float magnitude) {
        BetterWeaponTrait trait = new BetterWeaponTrait(name, MODID, TraitQuality.POSITIVE) {
            @Override
            public String getDescription() {
                return String.format(Locale.US, "+%d%% damage while in the Void", Math.round(this.magnitude * 100.0F - 100.0F));
            }

            @Override
            public float modifyDamageDealt(WeaponMaterial material, float baseDamage, DamageSource source, LivingEntity attacker, LivingEntity victim) {
                return inVoid(attacker) ? baseDamage * this.magnitude : baseDamage;
            }

            @Override
            public float modifyRangedDamageDealt(WeaponMaterial material, float baseDamage, DamageSource source, LivingEntity attacker, LivingEntity victim) {
                return inVoid(attacker) ? baseDamage * this.magnitude : baseDamage;
            }
        };
        trait.setMagnitude(magnitude).setMelee().setRanged().setThrowing();
        return trait;
    }

    public static final RegistryObject<WeaponTrait> VOIDTOUCHED = registerTrait(TRAITS, voidtouched("voidtouched", 1.3F));
    public static final RegistryObject<WeaponTrait> DEEP_VOIDTOUCHED = registerTrait(TRAITS, voidtouched("deep_voidtouched", 1.4F));

    /** Corrupt weapons wither their targets. Level is the wither amplifier + 1, magnitude the seconds. */
    public static final RegistryObject<WeaponTrait> CORRUPTION = registerTrait(TRAITS,
        new BetterWeaponTrait("corruption", MODID, TraitQuality.POSITIVE) {
            @Override
            public String getDescription() {
                return String.format(Locale.US, "Hits inflict Wither for %d seconds", Math.round(this.magnitude));
            }

            @Override
            public void onHitEntity(WeaponMaterial material, ItemStack stack, LivingEntity target, LivingEntity attacker, Entity projectile) {
                target.addEffect(new MobEffectInstance(MobEffects.WITHER, Math.round(this.magnitude * 20.0F), 0));
            }

            @Override
            public void onRangedHitEntity(WeaponMaterial material, ItemStack stack, LivingEntity target, LivingEntity attacker, Entity projectile) {
                target.addEffect(new MobEffectInstance(MobEffects.WITHER, Math.round(this.magnitude * 20.0F), 0));
            }
        }.setMagnitude(3.0F).setMelee().setRanged().setThrowing());

    public static final List<SpartanMaterial> MATERIALS = new ArrayList<>();

    public static final SpartanMaterial VOIDIC_CRYSTAL = material("voidic_crystal", ModTools.ItemTier.VOIDIC_CRYSTAL,
        "voidic_crystal", Rarity.RARE, VOIDTOUCHED);
    public static final SpartanMaterial CORRUPT = material("corrupt", ModTools.ItemTier.CORRUPT,
        "corrupt", Rarity.EPIC, DEEP_VOIDTOUCHED, CORRUPTION);

    public static final RegistryObject<CreativeModeTab> TAB = registerTab(TABS, MODID,
        () -> WEAPONS.get(CORRUPT, WeaponType.LONGSWORD).get(),
        (parameters, output) -> ITEMS.getEntries().forEach(item -> output.accept(item.get())));

    @SafeVarargs
    private static SpartanMaterial material(String name, Tier tier, String repairTag, Rarity rarity, RegistryObject<WeaponTrait>... traits) {
        TagKey<Item> repair = ItemTags.create(new ResourceLocation(MODID, "repair/" + repairTag));
        SpartanMaterial material = new SpartanMaterial(name, MODID, tier, repair, traits).setRarity(rarity);
        MATERIALS.add(material);
        return material;
    }

    private static boolean inVoid(LivingEntity entity) {
        return entity != null && entity.level().dimension().location().equals(VOID_DIMENSION);
    }

    public SpartanWeaponryVoidscape() {
        IEventBus bus = FMLJavaModLoadingContext.get().getModEventBus();
        registerSpartanWeapons(ITEMS);
        ITEMS.register(bus);
        TRAITS.register(bus);
        TABS.register(bus);
    }

    @Override
    public String modid() {
        return MODID;
    }

    @Override
    public List<SpartanMaterial> getMaterials() {
        return MATERIALS;
    }

    @Override
    public WeaponMap getWeaponMap() {
        return WEAPONS;
    }
}
