/**
 * Spartan Weaponry: Voidscape. Every base Voidscape gear tier (Voidic Crystal, Corrupt, Titanite, Ichor,
 * Astral) for every Spartan weapon type, using Voidscape's own tool tiers so stats match its swords.
 * Each tier carries Voidscape's Voidic Damage (1-5, like its swords and bows), a Voidtouched bonus in
 * the Void, and from Corrupt up a tier-specific special. Recipes are Voidscape's smithing chain:
 * netherite -> voidic crystal -> corrupt -> titanite -> ichor -> astral (generated by tools/gen_assets.py).
 */
@Mod(SpartanWeaponryVoidscape.MODID)
public class SpartanWeaponryVoidscape extends SpartanAddon {
    public static final String MODID = "spartanweaponryvoidscape";
    private static final ResourceLocation VOID_DIMENSION = new ResourceLocation("voidscape", "void");

    public static final WeaponMap WEAPONS = new WeaponMap();
    public static final DeferredRegister<Item> ITEMS = itemRegister(MODID);
    public static final DeferredRegister<WeaponTrait> TRAITS = traitRegister(MODID);
    public static final DeferredRegister<CreativeModeTab> TABS = tabRegister(MODID);

    // Levelled traits use a plain type ("voidtouched") plus setLevel: Spartan Toolkit registers them as
    // "<type>_<level>" and Spartan shows "<name> <roman level>". Putting the number in the type as well
    // doubled it ("voidtouched_1_1") and broke both the tooltips and the material trait tags.

    /** Voidtouched I-V: extra damage while the wielder is inside Voidscape's Void. */
    private static RegistryObject<WeaponTrait> voidtouched(int level, float multiplier) {
        BetterWeaponTrait trait = new BetterWeaponTrait("voidtouched", MODID, TraitQuality.POSITIVE) {
            @Override
            public String getDescription() {
                return String.format(Locale.US, "+%d%% damage while in the Void", Math.round(this.magnitude * 100.0F - 100.0F));
            }

            @Override
            public float modifyDamageDealt(WeaponMaterial material, float baseDamage, DamageSource source, LivingEntity attacker, LivingEntity victim) {
                return inVoid(attacker) ? baseDamage * this.magnitude : baseDamage;
            }

            @Override
            public float modifyRangedDamageDealt(WeaponMaterial material, float baseDamage, DamageSource source, LivingEntity attacker, LivingEntity victim) {
                return inVoid(attacker) ? baseDamage * this.magnitude : baseDamage;
            }
        };
        trait.setMagnitude(multiplier).setLevel(level);
        trait.setMelee().setRanged().setThrowing();
        return registerTrait(TRAITS, trait);
    }

    /** Voidic Damage I-V: Voidscape's own voidic damage attributes, same amounts as its swords and bows. */
    private static RegistryObject<WeaponTrait> voidicDamage(int level) {
        UUID meleeId = UUID.nameUUIDFromBytes((MODID + ":voidic_dmg_" + level).getBytes(StandardCharsets.UTF_8));
        UUID arrowId = UUID.nameUUIDFromBytes((MODID + ":voidic_arrow_dmg_" + level).getBytes(StandardCharsets.UTF_8));
        BetterWeaponTrait trait = new BetterWeaponTrait("voidic_damage", MODID, TraitQuality.POSITIVE) {
            @Override
            public String getDescription() {
                return String.format(Locale.US, "+%d Voidic Damage and Voidic Arrow Damage", level);
            }

            @Override
            public void onModifyAttributes(ImmutableMultimap.Builder<Attribute, AttributeModifier> builder) {
                builder.put(ModAttributes.VOIDIC_DMG.get(), new AttributeModifier(meleeId, "Voidic damage", level, AttributeModifier.Operation.ADDITION));
                builder.put(ModAttributes.VOIDIC_ARROW_DMG.get(), new AttributeModifier(arrowId, "Voidic arrow damage", level, AttributeModifier.Operation.ADDITION));
            }
        };
        trait.setLevel(level);
        trait.setMelee().setRanged().setThrowing();
        return registerTrait(TRAITS, trait);
    }

    /** A tier special: applies an effect to whatever the weapon hits, in melee, thrown or shot. */
    private static RegistryObject<WeaponTrait> onHit(String name, String description, BiConsumer<LivingEntity, LivingEntity> effect) {
        BetterWeaponTrait trait = new BetterWeaponTrait(name, MODID, TraitQuality.POSITIVE) {
            @Override
            public String getDescription() {
                return description;
            }

            @Override
            public void onHitEntity(WeaponMaterial material, ItemStack stack, LivingEntity target, LivingEntity attacker, Entity projectile) {
                effect.accept(target, attacker);
            }

            @Override
            public void onRangedHitEntity(WeaponMaterial material, ItemStack stack, LivingEntity target, LivingEntity attacker, Entity projectile) {
                effect.accept(target, attacker);
            }
        };
        trait.setMelee().setRanged().setThrowing();
        return registerTrait(TRAITS, trait);
    }

    public static final RegistryObject<WeaponTrait> VOIDTOUCHED_1 = voidtouched(1, 1.30F);
    public static final RegistryObject<WeaponTrait> VOIDTOUCHED_2 = voidtouched(2, 1.40F);
    public static final RegistryObject<WeaponTrait> VOIDTOUCHED_3 = voidtouched(3, 1.50F);
    public static final RegistryObject<WeaponTrait> VOIDTOUCHED_4 = voidtouched(4, 1.60F);
    public static final RegistryObject<WeaponTrait> VOIDTOUCHED_5 = voidtouched(5, 1.75F);

    public static final RegistryObject<WeaponTrait> VOIDIC_DAMAGE_1 = voidicDamage(1);
    public static final RegistryObject<WeaponTrait> VOIDIC_DAMAGE_2 = voidicDamage(2);
    public static final RegistryObject<WeaponTrait> VOIDIC_DAMAGE_3 = voidicDamage(3);
    public static final RegistryObject<WeaponTrait> VOIDIC_DAMAGE_4 = voidicDamage(4);
    public static final RegistryObject<WeaponTrait> VOIDIC_DAMAGE_5 = voidicDamage(5);

    /** Corrupt: the Void's rot. */
    public static final RegistryObject<WeaponTrait> CORRUPTION = onHit("corruption", "Hits inflict Wither for 3 seconds",
        (target, attacker) -> target.addEffect(new MobEffectInstance(MobEffects.WITHER, 60, 0)));
    /** Titanite: purified by the Null Servants, it strips its target's blessings. */
    public static final RegistryObject<WeaponTrait> PURGE = onHit("purge", "Hits remove the target's beneficial effects",
        (target, attacker) -> new ArrayList<>(target.getActiveEffects()).stream()
            .filter(effect -> effect.getEffect().isBeneficial())
            .forEach(effect -> target.removeEffect(effect.getEffect())));
    /** Ichor: "Blood of the Gods" burns. */
    public static final RegistryObject<WeaponTrait> ICHOR_BURN = onHit("ichor_burn", "Hits set the target ablaze for 4 seconds",
        (target, attacker) -> target.setSecondsOnFire(4));
    /** Astral: star-touched targets are marked and slowed. */
    public static final RegistryObject<WeaponTrait> STARSTRUCK = onHit("starstruck", "Hits make the target glow and slow it for 3 seconds",
        (target, attacker) -> {
            target.addEffect(new MobEffectInstance(MobEffects.GLOWING, 60, 0));
            target.addEffect(new MobEffectInstance(MobEffects.MOVEMENT_SLOWDOWN, 60, 1));
        });

    public static final List<SpartanMaterial> MATERIALS = new ArrayList<>();

    public static final SpartanMaterial VOIDIC_CRYSTAL = material("voidic_crystal", ModTools.ItemTier.VOIDIC_CRYSTAL, Rarity.RARE,
        VOIDIC_DAMAGE_1, VOIDTOUCHED_1);
    public static final SpartanMaterial CORRUPT = material("corrupt", ModTools.ItemTier.CORRUPT, Rarity.EPIC,
        VOIDIC_DAMAGE_2, VOIDTOUCHED_2, CORRUPTION);
    public static final SpartanMaterial TITANITE = material("titanite", ModTools.ItemTier.TITANITE, Rarity.EPIC,
        VOIDIC_DAMAGE_3, VOIDTOUCHED_3, PURGE);
    public static final SpartanMaterial ICHOR = material("ichor", ModTools.ItemTier.ICHOR, Rarity.EPIC,
        VOIDIC_DAMAGE_4, VOIDTOUCHED_4, ICHOR_BURN);
    public static final SpartanMaterial ASTRAL = material("astral", ModTools.ItemTier.ASTRAL, Rarity.EPIC,
        VOIDIC_DAMAGE_5, VOIDTOUCHED_5, STARSTRUCK);

    public static final RegistryObject<CreativeModeTab> TAB = registerTab(TABS, MODID,
        () -> WEAPONS.get(ASTRAL, WeaponType.LONGSWORD).get(),
        (parameters, output) -> ITEMS.getEntries().forEach(item -> output.accept(item.get())));

    @SafeVarargs
    private static SpartanMaterial material(String name, Tier tier, Rarity rarity, RegistryObject<WeaponTrait>... traits) {
        TagKey<Item> repair = ItemTags.create(new ResourceLocation(MODID, "repair/" + name));
        SpartanMaterial material = new SpartanMaterial(name, MODID, tier, repair, traits).setRarity(rarity);
        MATERIALS.add(material);
        return material;
    }

    private static boolean inVoid(LivingEntity entity) {
        return entity != null && entity.level().dimension().location().equals(VOID_DIMENSION);
    }

    public SpartanWeaponryVoidscape() {
        IEventBus bus = FMLJavaModLoadingContext.get().getModEventBus();
        registerSpartanWeapons(ITEMS);
        ITEMS.register(bus);
        TRAITS.register(bus);
        TABS.register(bus);
    }

    @Override
    public String modid() {
        return MODID;
    }

    @Override
    public List<SpartanMaterial> getMaterials() {
        return MATERIALS;
    }

    @Override
    public WeaponMap getWeaponMap() {
        return WEAPONS;
    }
}
